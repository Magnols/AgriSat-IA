CREATE TABLE AREA (
    ID_AREA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    DESCRICAO VARCHAR2(200)
);

CREATE TABLE EQUIPAMENTO (
    ID_EQUIPAMENTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    LIMITE_CONSUMO NUMBER(10,2) NOT NULL,
    ID_AREA NUMBER NOT NULL,
    CONSTRAINT FK_EQUIP_AREA FOREIGN KEY (ID_AREA) REFERENCES AREA (ID_AREA)
);

CREATE TABLE LEITURA_ENERGIA (
    ID_LEITURA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DATA_HORA TIMESTAMP NOT NULL,
    CONSUMO NUMBER(10,2) NOT NULL,
    ID_EQUIPAMENTO NUMBER NOT NULL,
    CONSTRAINT FK_LEITURA_EQUIP FOREIGN KEY (ID_EQUIPAMENTO) REFERENCES EQUIPAMENTO (ID_EQUIPAMENTO)
);

CREATE TABLE ALERTA (
    ID_ALERTA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DESCRICAO VARCHAR2(200) NOT NULL,
    DATA_HORA TIMESTAMP NOT NULL,
    ID_EQUIPAMENTO NUMBER NOT NULL,
    CONSTRAINT FK_ALERTA_EQUIP FOREIGN KEY (ID_EQUIPAMENTO) REFERENCES EQUIPAMENTO (ID_EQUIPAMENTO)
);

CREATE TABLE CONSUMO_DIARIO (
    ID_CONSUMO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DATA_REFERENCIA DATE NOT NULL,
    TOTAL_CONSUMO NUMBER(10,2) NOT NULL,
    ID_EQUIPAMENTO NUMBER NOT NULL,
    CONSTRAINT FK_CONSUMO_EQUIP FOREIGN KEY (ID_EQUIPAMENTO) REFERENCES EQUIPAMENTO (ID_EQUIPAMENTO)
);
